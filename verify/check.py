import json
from playwright.sync_api import sync_playwright
URL = "http://localhost:5173/"
OUT = "/workspace/aiatlas-app/verify/"
res = {}
with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={"width": 1440, "height": 900})
    pg.goto(URL, wait_until="networkidle"); pg.wait_for_timeout(2000)
    pg.screenshot(path=OUT + "desktop-full.png", full_page=True)
    res["markers_in_group"] = pg.evaluate("window.__atlasCluster.getLayers().length")
    res["count_text"] = pg.inner_text(".result-count")
    pg.click("button.methodology-button"); pg.wait_for_timeout(500)
    pg.screenshot(path=OUT + "desktop-methodology-modal.png")
    pg.click(".modal-backdrop", position={"x": 10, "y": 10}); pg.wait_for_timeout(300)
    res["modal_closed"] = pg.locator(".methodology-modal").count() == 0
    pg.click("button.pill:has-text('AI-native')"); pg.wait_for_timeout(800)
    res["ai_native_count"] = pg.inner_text(".result-count")
    pg.screenshot(path=OUT + "desktop-filter-ai-native.png", full_page=True)
    pg.click("button.reset-button")
    pg.fill(".search-box input", "tokyo"); pg.wait_for_timeout(500)
    res["search_tokyo"] = pg.inner_text(".result-count")
    pg.click("button.reset-button")
    pg.select_option(".select-row label:has-text('REGION') select", "Europe"); pg.wait_for_timeout(300)
    res["region_europe"] = pg.inner_text(".result-count")
    pg.select_option(".select-row label:has-text('OPERATOR') select", "Google"); pg.wait_for_timeout(300)
    res["europe_google"] = pg.inner_text(".result-count")
    pg.click("button.reset-button")
    pg.click("button.pill:has-text('Planned')"); pg.wait_for_timeout(300)
    res["planned"] = pg.inner_text(".result-count")
    pg.click("button.reset-button")
    # zoom so markers are unclustered, then click a single marker (Sydney - isolated)
    pg.evaluate("window.__atlasMap.setView([-33.8688,151.2093],5,{animate:false})"); pg.wait_for_timeout(1200)
    pg.locator(".atlas-marker").first.click(force=True); pg.wait_for_timeout(1500)
    res["detail_h3"] = pg.inner_text(".detail-card h3")
    res["center_after_click"] = pg.evaluate("(()=>{const c=window.__atlasMap.getCenter();return [c.lat.toFixed(2),c.lng.toFixed(2),window.__atlasMap.getZoom()]})()")
    res["selected_marker"] = pg.locator(".atlas-marker.is-selected").count()
    pg.evaluate("window.__atlasMap.setView([20,12],2,{animate:false})"); pg.wait_for_timeout(800)
    pg.click(".nearby-item:has-text('Colossus 2')"); pg.wait_for_timeout(1500)
    res["list_click_h3"] = pg.inner_text(".detail-card h3")
    res["list_click_center"] = pg.evaluate("(()=>{const c=window.__atlasMap.getCenter();return [c.lat.toFixed(2),c.lng.toFixed(2),window.__atlasMap.getZoom()]})()")
    pg.screenshot(path=OUT + "desktop-selected-marker.png")
    m = b.new_page(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True)
    m.goto(URL, wait_until="networkidle"); m.wait_for_timeout(2000)
    m.screenshot(path=OUT + "mobile-full.png", full_page=True)
    b.close()
print(json.dumps(res, indent=1))
